export const ROOMS: readonly RoomDef[] = [cell, cloister, gallery, cistern, reliquary, approach, sanctum];

export const START_ROOM = "cell";

export function findRoom(id: string): RoomDef {
  const room = ROOMS.find((r) => r.id === id);
  if (!room) throw new Error(`Unknown room: ${id}`);
  return room;
}

