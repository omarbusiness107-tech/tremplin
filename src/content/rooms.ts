/**
 * World data. Each room is an ASCII grid; terrain characters are listed in
 * `TERRAIN_CHARS`, and the markers below place actors and pickups.
 *
 *   @  default player spawn        A  prayer altar (checkpoint)
 *   s  shambler                    t  thurifer          w  warden
 *   B  boss spawn
 *   D  double-jump relic           K  seal breaker      F  flask upgrade
 *   H  heart upgrade               $  tears
 *
 * Terrain: '#' stone, '=' one-way platform, '^' spikes, '|' sealed gate.
 * Every row in a room must be the same length or the loader throws.
 */

export type MarkerChar = "@" | "A" | "s" | "t" | "w" | "B" | "D" | "K" | "F" | "H" | "$";

export const MARKER_CHARS = new Set<string>(["@", "A", "s", "t", "w", "B", "D", "K", "F", "H", "$"]);

export interface DoorDef {
  id: string;
  /** Trigger area in tiles. */
  tx: number;
  ty: number;
  tw: number;
  th: number;
  to: { room: string; door: string };
  /** Tile the player's feet land on when arriving through this door. */
  spawn: { tx: number; ty: number; facing: 1 | -1 };
  /** Locked doors need this ability before they can be used. */
  requires?: "sealBreaker" | "doubleJump";
}

export interface RoomDef {
  id: string;
  name: string;
  rows: string[];
  doors: DoorDef[];
  /** Boss rooms seal their exits until the boss falls. */
  boss?: boolean;
  /** Drawn behind the tiles; picks a background mood. */
  mood?: "cell" | "cloister" | "gallery" | "cistern" | "reliquary" | "sanctum";
}

